#!/usr/bin/env python3
"""Write js/stream-data.js, the lines of the home page's data stream, from the atlas's checked series file.

Run from the site folder:  python3 -I tools/stream_data.py [path to the lab's motion/data/series.json]
Every figure in the stream is a field of that file; nothing is typed by hand. The script records the
source's path and SHA-256 in the output, so a changed source shows up as a changed header.
"""
import hashlib
import json
import pathlib
import sys

LAB_SERIES = (pathlib.Path.home() / "Documents/PhD/CGU/Dissertation/00 Full Dissertation"
              / "Claude Code/current/dataviz-lab/motion/data/series.json")
OUT = pathlib.Path(__file__).resolve().parent.parent / "js" / "stream-data.js"


def n(v):
    return f"{v:,}"


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else LAB_SERIES
    raw = src.read_bytes()
    d = json.loads(raw)
    a, f = d["avail"], d["facts"]

    items = []
    for i, year in enumerate(a["year"]):
        eligible, available = a["eligible"][i], a["eligible_available"][i]
        if not available:          # the release holds no statements for this year
            continue
        items.append(f"{year}  ELIGIBLE FIRMS {n(eligible)}")
        items.append(f"{year}  WITH A STATEMENT {n(available)} OF {n(eligible)}, {a['eligible_share'][i]:.1f}%")
    items += [
        f"{f['release']}  {n(f['records_total'])} ANNUAL RECORDS  {f['years']}",
        f"2021  LOCATED FIRMS {n(f['located_2021'])} OF {n(f['eligible_firms_2021'])}",
        f"{n(f['distinct_locations'])} DISTINCT COORDINATE PAIRS",
        f"2021  {n(f['largest_location_firms'])} FIRMS AT THE LARGEST REGISTERED ADDRESS",
        f"2021  {n(f['firms_at_100plus_locations'])} FIRMS AT ADDRESSES SHARED BY 100 OR MORE",
    ]
    for s in items:                # the atlas's on-screen rules
        assert ";" not in s and "—" not in s and "listed" not in s.lower(), s

    head = (f"/* Generated by tools/stream_data.py from {src.name} (sha256 {hashlib.sha256(raw).hexdigest()[:16]}),\n"
            f"   {f['release']}, released {f['release_date']}. Do not edit by hand: run the script again. */\n")
    OUT.write_text(head + "window.STREAM_ITEMS = " + json.dumps(items, ensure_ascii=False, indent=0) + ";\n")
    print(f"{len(items)} items written to {OUT}")


if __name__ == "__main__":
    main()
